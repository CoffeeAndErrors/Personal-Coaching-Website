import { NextResponse } from 'next/server';
import db from '@/lib/db';
import nodemailer from 'nodemailer';

export async function POST(request) {
  try {
    const { name, email, phone, message } = await request.json();

    if (!name || !email || !phone || !message) {
      return NextResponse.json({ error: 'Missing fields' }, { status: 400 });
    }

    // 1. Save to Database (Reliability Backup)
    await db.runPromise(
      'INSERT INTO contacts (name, email, phone, message) VALUES (?, ?, ?, ?)',
      [name, email, phone, message]
    );

    // 2. Trigger Email Notification (Instant Alert)
    const transporter = nodemailer.createTransport({
      host: process.env.SMTP_HOST,
      port: process.env.SMTP_PORT,
      secure: false, // true for 465, false for other ports
      auth: {
        user: process.env.SMTP_USER,
        pass: process.env.SMTP_PASS,
      },
    });

    // Only attempt to send if credentials exist
    if (process.env.SMTP_USER && process.env.SMTP_PASS) {
      const mailOptions = {
        from: `"LIFTINGMONK Intake" <${process.env.SMTP_USER}>`,
        to: process.env.NOTIFICATION_EMAIL || 'liftingmonkfitness@gmail.com',
        subject: `NEW INTAKE: ${name}`,
        html: `
          <div style="background-color: #000; color: #fff; padding: 40px; font-family: sans-serif; border-left: 4px solid #f97316;">
            <h1 style="text-transform: uppercase; letter-spacing: 2px; margin-bottom: 30px;">New Transformation Lead</h1>
            
            <div style="background-color: #111; padding: 20px; border: 1px solid #222; margin-bottom: 20px;">
              <p style="color: #666; text-transform: uppercase; font-size: 10px; font-weight: bold; margin-bottom: 5px;">Client Name</p>
              <p style="font-size: 18px; color: #f97316; font-weight: bold; margin: 0;">${name}</p>
            </div>

            <div style="background-color: #111; padding: 20px; border: 1px solid #222; margin-bottom: 20px;">
              <p style="color: #666; text-transform: uppercase; font-size: 10px; font-weight: bold; margin-bottom: 5px;">Mail ID</p>
              <p style="font-size: 18px; margin: 0;">${email}</p>
            </div>

            <div style="background-color: #111; padding: 20px; border: 1px solid #222; margin-bottom: 20px;">
              <p style="color: #666; text-transform: uppercase; font-size: 10px; font-weight: bold; margin-bottom: 5px;">Phone Number</p>
              <p style="font-size: 18px; margin: 0;">${phone}</p>
            </div>

            <div style="background-color: #111; padding: 20px; border: 1px solid #222;">
              <p style="color: #666; text-transform: uppercase; font-size: 10px; font-weight: bold; margin-bottom: 5px;">Transformation Details</p>
              <p style="font-size: 16px; line-height: 1.6; color: #ccc; margin: 0;">${message}</p>
            </div>

            <p style="margin-top: 40px; color: #444; font-size: 12px; text-transform: uppercase;">Generated by LIFTINGMONK Landing Page</p>
          </div>
        `,
      };

      await transporter.sendMail(mailOptions);
    } else {
      console.warn('SMTP credentials missing. Lead saved to DB but email notification skipped.');
    }

    return NextResponse.json({ success: true });
  } catch (error) {
    console.error('Contact API Error:', error);
    return NextResponse.json({ error: 'Internal Server Error' }, { status: 500 });
  }
}